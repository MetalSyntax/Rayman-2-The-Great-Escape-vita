#!/usr/bin/env python3
"""Writes docs/imports.md: every import of the Mach-O -> shim file -> handler -> status.

Status: real (implemented), stub (deliberate no-op / offline / dummy), host-class (ObjC class created on
demand by objc.c, methods in objc.c/uikit.c host_method tables), const (NSString constant),
UNIMPL (no table entry: bound to the logging stub ml_unimpl_entry / a zero data block).
Uso: python3 -I tools/imports_table.py [decompiled/macho/imports.txt] [docs/imports.md]
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMPORTS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'decompiled/macho/imports.txt')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'docs/imports.md')

# Handlers that intentionally do nothing useful (offline, IGP shop UI, dummies).
STUBS = {'d_ok', 'd_null', 'd_net_fail', 'd_gethostbyname', 'd_inet_aton', 'objc_noop', 'cg_noop', 'cg_null',
         'cf_null', 'sc_ok', 'sc_null', 'sc_reachability_flags', 'cg_dummy_image', 'cc_md5', 'd_host_statistics',
         'd_host_page_size', 'd_mach_host_self', 'aq_set_property', 'ok', 'cg_ColorSpaceCreate',
         'd_sjlj_noop', 'd_sjlj_resume', 'objc_begin_catch'}
ORDER = ['patch.c', 'cxx.c', 'darwin.c', 'gles.c', 'coreaudio.c', 'objc.c', 'uikit.c']  # imports.c order

entry = re.compile(r'\b(?:F|D|V|AL|F_RAW|D_RAW|V_RAW)\(\s*"?([A-Za-z_$][\w$]*)"?\s*(?:,\s*&?([\w]+))?')
raw = re.compile(r'\{\s*"(_[\w$]+)",\s*\(uintptr_t\)&?(\w+)')
table = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'source', '*.c'))):
    fn = os.path.basename(path)
    if fn.startswith('._'):
        continue
    src = open(path, errors='ignore').read()
    for m in entry.finditer(src):
        name = m.group(1) if m.group(0).startswith(('F_RAW', 'D_RAW', 'V_RAW')) else '_' + m.group(1)
        table.setdefault(name, []).append((fn, m.group(2) or m.group(1)))
    for m in raw.finditer(src):
        table.setdefault(m.group(1), []).append((fn, m.group(2)))
consts = re.search(r'const_names\[\] = \{(.*?)\};', open(os.path.join(ROOT, 'source/objc.c')).read(), re.S)
consts = set(re.findall(r'"(\w+)"', consts.group(1))) if consts else set()

rows, counts = [], {}
for imp in [l.strip() for l in open(IMPORTS) if l.strip()]:
    hits = sorted(table.get(imp, []), key=lambda h: ORDER.index(h[0]) if h[0] in ORDER else 99)
    if hits:
        fn, h = hits[0]
        st = 'stub' if h in STUBS or fn == 'patch.c' else 'real'
    elif imp.startswith(('_OBJC_CLASS_$_', '_OBJC_METACLASS_$_')):
        fn, h, st = 'objc.c', 'host_get() on demand', 'host-class'
    elif imp == '___CFConstantStringClassReference':
        fn, h, st = 'objc.c', 'c_NSString', 'real'
    elif imp[1:] in consts:
        fn, h, st = 'objc.c', 'const_values[] (NSString)', 'const'
    else:
        fn, h, st = '-', 'ml_unimpl_entry / zero block', 'UNIMPL'
    counts[st] = counts.get(st, 0) + 1
    rows.append(f'| `{imp}` | {fn} | `{h}` | {st} |')

with open(OUT, 'w') as f:
    f.write('# Rayman 2 imports -> loader shims\n\n')
    f.write('Generated by `python3 -I tools/imports_table.py` from `decompiled/macho/imports.txt` (nm -u, '
            f'{len(rows)} symbols) and the import tables in `source/*.c` (lookup order: {", ".join(ORDER)}).\n\n')
    f.write('Totals: ' + ', '.join(f'**{k}** {v}' for k, v in sorted(counts.items())) + '\n\n')
    f.write('Legend: real = implemented; stub = deliberate no-op/offline/dummy (network, Gameloft IGP shop UI, '
            'C++ exceptions); host-class = ObjC class created on demand (methods in objc.c / uikit.c, unknown '
            'selectors log `[OBJC] unhandled` once and return nil); const = NSString constant; UNIMPL = bound to '
            'the logging stub (`[UNIMPL]` lines in the log).\n\n')
    f.write('| Import | Shim file | Handler | Status |\n|---|---|---|---|\n')
    f.write('\n'.join(rows) + '\n')
print(OUT, counts)
